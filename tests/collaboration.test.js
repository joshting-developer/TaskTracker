const now = () => new Date().toISOString();
const request = (input) => ({ ...input, requestId: randomUUID() });
test('舊單人資料只歸第一個工作空間, 邀請過期與使用後不可重用', (t) => {
  const store = createSqliteStore(':memory:'); t.after(() => store.close());
  const old = createService(store, { uuid: randomUUID, now });
  const project = old.createProject(request({ name: '舊專案', code: 'OLD' }));
  old.createIssue(request({ projectId: project.id, title: '保留資料', assignee: '我' }));
  let timestamp = now();
  const auth = createAuth(store, { now: () => timestamp });
  const first = auth.register({ email: 'first@example.test', name: 'First', password: 'local-test-password', workspaceName: 'First' });
  const context = auth.resolve(first.token);
  assert.equal(tenantStore(store, context.workspace.id).transaction(tx => tx.list('issues'))[0].assignee, context.user.id);
  assert.equal(store.transaction(tx => tx.list('issues'))[0].assignee, '我', '保留原始記錄');
  const next = auth.register({ email: 'next@example.test', name: 'Next', password: 'local-test-password', workspaceName: 'Next' });
  assert.equal(tenantStore(store, auth.resolve(next.token).workspace.id).transaction(tx => tx.list('issues')).length, 0);
  const invite = auth.invite(context, { email: 'join@example.test' });
  auth.register({ email: 'join@example.test', name: 'Join', password: 'local-test-password', inviteToken: invite.token });
  assert.throws(() => auth.register({ email: 'other@example.test', name: 'Other', password: 'local-test-password', inviteToken: invite.token }), { code: 'INVALID_INPUT' });
  const expiring = auth.invite(context, { email: 'late@example.test' });
  timestamp = new Date(Date.parse(timestamp) + 8 * 86400000).toISOString();
  assert.throws(() => auth.register({ email: 'late@example.test', name: 'Late', password: 'local-test-password', inviteToken: expiring.token }), { code: 'INVALID_INPUT' });
  assert.throws(() => auth.resolve(first.token), { code: 'UNAUTHENTICATED' });
});
function fixture(t) {
  const store = createSqliteStore(':memory:'); t.after(() => store.close());
  const auth = createAuth(store);
  const owner = auth.register({ email: 'owner@example.test', name: 'Josh', password: 'local-test-password', workspaceName: '產品團隊' });
  const context = auth.resolve(owner.token);
  const serviceFor = (ctx) => createService(tenantStore(store, ctx.workspace.id), { uuid: randomUUID, now, actor: ctx.user.name, userId: ctx.user.id, role: ctx.role, workspace: ctx.workspace });
  const admin = serviceFor(context);
  const project = admin.createProject(request({ name: '網站', code: 'WEB' }));
  return { store, auth, owner, context, serviceFor, admin, project };
}
test('工作空間隔離、單次限時邀請、身分綁定與成員越權', (t) => {
  const { auth, context, serviceFor, admin, project } = fixture(t);
  const foreign = auth.register({ email: 'other@example.test', name: 'Other', password: 'local-test-password', workspaceName: '其他團隊' });
  const other = serviceFor(auth.resolve(foreign.token));
  assert.equal(other.getWorkspace().projects.length, 0);
  assert.throws(() => other.createIssue(request({ projectId: project.id, title: '跨租戶' })), { code: 'NOT_FOUND' });
  const savedView = admin.createSavedView(request({ projectId: project.id, name: '團隊 Bug', visibility: 'team', filters: { type: 'bug' } }));
  assert.equal(other.getWorkspace().savedViews.length, 0);
  assert.throws(() => other.updateSavedView(request({ id: savedView.id, expectedRevision: 1, name: '跨租戶', filters: {} })), { code: 'NOT_FOUND' });
  const invite = auth.invite(context, { email: 'member@example.test' });
  assert.throws(() => auth.register({ email: 'wrong@example.test', name: 'Wrong', password: 'local-test-password', inviteToken: invite.token }), { code: 'INVALID_INPUT' });
  const member = auth.register({ email: 'member@example.test', name: 'Mei', password: 'local-test-password', inviteToken: invite.token });
  const memberContext = auth.resolve(member.token);
  const teammate = serviceFor(memberContext);
  assert.equal(memberContext.workspace.id, context.workspace.id);
  assert.equal(teammate.getWorkspace().projects.length, 1);
  assert.throws(() => auth.invite(memberContext, { email: 'intruder@example.test' }), { code: 'FORBIDDEN' });
  assert.throws(() => teammate.updateStatuses(request({ projectId: project.id, expectedRevision: 1, statuses: project.statuses })), { code: 'FORBIDDEN' });
  const issueInput = request({ projectId: project.id, title: '登入', assignee: memberContext.user.id });
  const issue = admin.createIssue(issueInput);
  assert.equal(admin.getWorkspace().notifications.length, 1);
  assert.deepEqual(admin.createIssue(issueInput), issue);
  assert.equal(admin.getWorkspace().notifications.length, 1);
  const own = teammate.createIssue(issueInput);
  assert.notEqual(own.id, issue.id, '重試識別碼須按使用者隔離');
  const entry = teammate.logTime(request({ issueId: issue.id, workDate: dateInTaipei(), minutes: 90, userId: context.user.id }));
  assert.equal(entry.userId, memberContext.user.id, '忽略前端冒用的身分');
  assert.throws(() => admin.updateTime(request({ id: entry.id, expectedRevision: 1, workDate: entry.workDate, minutes: 1 })), { code: 'FORBIDDEN' });
  assert.throws(() => other.updateTime(request({ id: entry.id, expectedRevision: 1, workDate: entry.workDate, minutes: 1 })), { code: 'NOT_FOUND' });
  const data = JSON.stringify(teammate.getWorkspace());
  assert.ok(!data.includes('passwordHash') && !data.includes('local-test-password'));
  auth.logout(member.token);
  assert.throws(() => auth.resolve(member.token), { code: 'UNAUTHENTICATED' });
});
test('Epic 關聯、完成／重開、自訂狀態、工時修正與加總', (t) => {
  const { admin, project, context } = fixture(t);
  const make = (input) => admin.createIssue(request({ projectId: project.id, title: '工作', ...input }));
  const epic = make({ type: 'epic', title: '會員系統' });
  const task = make({ epicId: epic.id, estimateMinutes: 180 });
  const bug = make({ epicId: epic.id, type: 'bug' });
  assert.throws(() => make({ type: 'epic', epicId: epic.id }), { code: 'INVALID_INPUT' });
  assert.throws(() => admin.updateIssue(request({ id: epic.id, expectedRevision: 1, type: 'task' })), { code: 'INVALID_INPUT' });
  assert.throws(() => admin.updateIssue(request({ id: epic.id, expectedRevision: 1, state: 'done' })), { code: 'INVALID_INPUT' });
  const second = admin.createProject(request({ name: '另一專案', code: 'NEXT' }));
  assert.throws(() => admin.createIssue(request({ projectId: second.id, title: '不同專案', epicId: epic.id })), { code: 'INVALID_INPUT' });
  const configured = admin.updateStatuses(request({ projectId: project.id, expectedRevision: 1, statuses: [...project.statuses, { id: 'review', label: '待測試', color: '#9876ab', category: 'active' }, { id: 'canceled', label: '取消', color: '#999999', category: 'canceled' }] }));
  const inReview = admin.updateIssue(request({ id: task.id, expectedRevision: 1, state: 'review' }));
  assert.throws(() => admin.updateStatuses(request({ projectId: project.id, expectedRevision: 2, statuses: project.statuses })), { code: 'INVALID_INPUT' });
  assert.throws(() => admin.updateStatuses(request({ projectId: project.id, expectedRevision: 1, statuses: configured.statuses })), { code: 'REVISION_CONFLICT' });
  const entryInput = request({ issueId: task.id, workDate: dateInTaipei(), minutes: 90, note: '實作登入' });
  const entry = admin.logTime(entryInput);
  assert.deepEqual(admin.logTime(entryInput), entry);
  assert.throws(() => admin.logTime(request({ issueId: epic.id, workDate: dateInTaipei(), minutes: 60 })), { code: 'INVALID_INPUT' });
  assert.throws(() => admin.logTime(request({ issueId: task.id, workDate: '2999-01-01', minutes: 60 })), { code: 'INVALID_INPUT' });
  assert.throws(() => admin.logTime(request({ issueId: task.id, workDate: dateInTaipei(), minutes: 1400 })), { code: 'INVALID_INPUT' });
  const edited = admin.updateTime(request({ id: entry.id, expectedRevision: 1, workDate: entry.workDate, minutes: 120, note: '補登' }));
  assert.throws(() => admin.updateTime(request({ id: entry.id, expectedRevision: 1, workDate: entry.workDate, minutes: 60 })), { code: 'REVISION_CONFLICT' });
  assert.equal(edited.history.length, 2);
  admin.updateIssue(request({ id: task.id, expectedRevision: inReview.revision, state: 'done' }));
  admin.updateIssue(request({ id: bug.id, expectedRevision: 1, state: 'canceled' }));
  const closed = admin.updateIssue(request({ id: epic.id, expectedRevision: 1, state: 'done' }));
  let data = admin.getWorkspace();
  let summary = epicSummary(closed, data.issues, data.timeEntries, configured);
  assert.equal(summary.percent, 100); assert.equal(summary.canceled, 1); assert.equal(summary.spentMinutes, 120);
  assert.equal(summary.estimateMinutes, 180);
  admin.updateIssue(request({ id: bug.id, expectedRevision: 2, state: 'todo' }));
  data = admin.getWorkspace(); summary = epicSummary(closed, data.issues, data.timeEntries, configured);
  assert.equal(summary.percent, 50); assert.equal(summary.needsReview, true);
  assert.equal(data.issues.find((item) => item.id === epic.id).state, 'done');
  admin.voidTime(request({ id: entry.id, expectedRevision: edited.revision }));
  data = admin.getWorkspace();
  assert.equal(epicSummary(closed, data.issues, data.timeEntries, configured).spentMinutes, 0);
  assert.equal(data.timeEntries[0].userId, context.user.id);
});
test('SMTP 檢查只連線驗證、強制 TLS、隱藏私密資訊, 不寄信', async () => {
  assert.deepEqual(createSmtp({}).status(), { configured: false, mode: 'preview', provider: '尚未設定', canSend: false });
  let options, verified = false, closed = false;
  const smtp = createSmtp({ SMTP_HOST: 'smtp.example.test', SMTP_FROM: 'team@example.test', SMTP_USER: 'user', SMTP_PASSWORD: 'private' }, (input) => {
    options = input;
    return { verify: async () => { verified = true; }, close: () => { closed = true; }, sendMail: () => assert.fail('禁止寄信') };
  });
  assert.equal((await smtp.verify()).verified, true);
  assert.ok(verified && closed && options.requireTLS);
  assert.ok(!JSON.stringify(smtp.status()).includes('private'));
});
test('正式本機 API 要求 session, cookie 及登出, 拒絕跨租戶 ID', async (t) => {
  const { auth, owner, serviceFor, project } = fixture(t);
  const server = createApiServer(null, { auth, serviceFor });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const call = (path, input = {}, token) => fetch(`http://127.0.0.1:${server.address().port}/api/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(token ? { Cookie: `tt_session=${token}` } : {}) }, body: JSON.stringify(input) });
  assert.equal((await call('rpc/getWorkspace')).status, 401);
  assert.equal((await call('rpc/getWorkspace', {}, owner.token)).status, 200);
  const response = await call('auth/login', { email: 'owner@example.test', password: 'local-test-password' });
  assert.equal(response.status, 200); assert.match(response.headers.get('set-cookie'), /HttpOnly; SameSite=Strict/);
  assert.equal((await call('auth/login', { email: 'owner@example.test', password: 'wrong' })).status, 401);
  const other = auth.register({ email: 'foreign@example.test', name: 'Foreign', password: 'local-test-password', workspaceName: 'Foreign' });
  assert.equal((await call('rpc/createIssue', request({ projectId: project.id, title: '跨租戶' }), other.token)).status, 404);
  assert.equal((await call('auth/logout', {}, owner.token)).status, 200);
  assert.equal((await call('rpc/getWorkspace', {}, owner.token)).status, 401);
});

const port = Number(process.env.E2E_FRONTEND_PORT || 5175), baseURL = `http://127.0.0.1:${port}`;
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';
import { chromium } from 'playwright';

if (!process.env.E2E_API_URL) throw new Error('請設定隔離 E2E_API_URL');
let vite, browser;
const artifacts = 'artifacts/markdown';
mkdirSync(artifacts, { recursive: true });
try {
  vite = await createServer({ server: { host: '127.0.0.1', port, strictPort: true, proxy: { '/api': process.env.E2E_API_URL } } });
  await vite.listen();
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000);
  const failures = [], unwantedRequests = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => { if (request.url().includes('markdown-test.invalid')) unwantedRequests.push(request.url()); });
  await page.goto(`${baseURL}/login`);
  await page.evaluate(async () => (await import('/tools/fixtures/verified-api.js')).api.register({ name: 'Markdown檢查', email: `markdown-${crypto.randomUUID()}@example.test`, password: 'markdown-test-password', workspaceName: '內容編輯驗證' }));
  await page.reload();
  const home = page.getByRole('region', { name: '首頁小待辦', exact: true });
  const quick = home.getByRole('group', { name: '快速新增待辦編輯器', exact: true });
  const input = quick.getByLabel('快速新增待辦', { exact: true });
  await input.fill('格式測試');
  await input.evaluate(element => element.setSelectionRange(0, element.value.length));
  await quick.getByRole('button', { name: '快速新增待辦：粗體', exact: true }).click();
  assert.equal(await input.inputValue(), '**格式測試**');
  await input.press('ControlOrMeta+z'); assert.equal(await input.inputValue(), '格式測試');
  await input.press('ControlOrMeta+Shift+z'); assert.equal(await input.inputValue(), '**格式測試**');
  await input.fill('中文輸入');
  await input.dispatchEvent('compositionstart');
  await input.dispatchEvent('keydown', { key: 'b', ctrlKey: true, isComposing: true });
  assert.equal(await input.inputValue(), '中文輸入');
  await input.dispatchEvent('compositionend');
  await input.fill('會議速記'); await input.press('Enter');
  assert.equal(await home.locator('.todo-row').count(), 0, 'Enter只換行，不建立待辦');
  const source = '**會議速記**\n\n- [ ] 補上測試\n- [x] 準備快照\n\n[文件](https://example.com/docs)\n\n```js\nconst ready = true;\n```\n';
  await input.fill(source);
  await quick.getByRole('tab', { name: '預覽', exact: true }).click();
  const preview = quick.getByRole('tabpanel', { name: '預覽', exact: true });
  await preview.locator('strong').getByText('會議速記', { exact: true }).waitFor();
  assert.equal(await preview.locator('input[type="checkbox"]:disabled').count(), 2);
  assert.equal(await preview.locator('input:checked').count(), 1);
  await preview.locator('pre code').getByText('const ready = true;', { exact: false }).waitFor();
  await quick.getByRole('tab', { name: '編輯', exact: true }).click();
  assert.equal(await input.inputValue(), source);
  await home.getByRole('button', { name: '加入待辦', exact: true }).click();
  let row = home.locator('.todo-row').filter({ has: page.locator('summary', { hasText: '會議速記' }) });
  await row.waitFor(); await row.locator('.todo-content > summary').click();
  await row.locator('.todo-note input[type="checkbox"]:disabled').first().waitFor({state:'attached'});
  assert.equal(await row.locator('.todo-note input[type="checkbox"]:disabled').count(), 2);
  const stored = await page.evaluate(async () => (await (await import('/tools/fixtures/verified-api.js')).api.getTodos()).todos[0]);
  assert.equal(stored.content, source);
  row = home.locator(`[data-todo-id="${stored.id}"]`);
  await row.getByLabel('待辦操作').click(); await row.getByRole('button', { name: '編輯', exact: true }).click();
  assert.equal(await row.getByLabel('編輯待辦內容', { exact: true }).inputValue(), source);
  await row.getByRole('tab', { name: '預覽', exact: true }).click();
  await home.getByRole('tab', { name: /我交辦的/ }).click();
  await home.getByRole('button', { name: '返回草稿', exact: true }).click();
  await row.getByLabel('編輯待辦內容', { exact: true }).waitFor();
  assert.equal(await row.getByLabel('編輯待辦內容', { exact: true }).inputValue(), source);
  await page.waitForFunction(() => document.querySelector('[aria-label="編輯待辦內容"]') === document.activeElement);

  page.once('dialog', dialog => dialog.accept());
  await row.getByRole('button', { name: '取消修改', exact: true }).click();

  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
    if (width === 390) await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
    await input.fill(source);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${artifacts}/todo-${width}.png`, fullPage: true });
    await input.fill('');
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const project = await page.evaluate(async () => (await import('/tools/fixtures/verified-api.js')).api.createProject({ name: 'Markdown卡片', code: 'MARK', requestId: crypto.randomUUID() }));
  await page.getByRole('button', { name: '重新整理工作空間', exact: true }).click();
  await row.getByLabel('待辦操作').click(); await row.getByRole('button', { name: '轉成正式卡片', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '轉成正式卡片', exact: true });
  assert.equal(await panel.getByLabel('描述', { exact: true }).inputValue(), source);
  await panel.getByLabel('專案', { exact: true }).selectOption(project.id);
  await panel.getByRole('button', { name: '建立卡片並完成轉換', exact: true }).click();
  await panel.waitFor({ state: 'hidden' });
  const issue = await page.evaluate(async () => (await (await import('/tools/fixtures/verified-api.js')).api.getWorkspace()).issues[0]);
  assert.equal(issue.description, source);
  await page.goto(`${baseURL}/app/#/projects/${project.id}/issues/${issue.id}?detail=1`);
  const detail = page.getByRole('region', { name: '任務完整頁', exact: true });
  await detail.getByRole('heading', { name: '會議速記', exact: true }).waitFor();
  const danger = '# 安全顯示\n\n<script>window.markdownExecuted = true</script>\n<img src="https://markdown-test.invalid/pixel" onerror="window.markdownExecuted = true">\n\n[危險](javascript:alert(1))\n[編碼危險](java&#x73;cript:alert(1))\n![圖片](https://markdown-test.invalid/image)\n<svg onload="window.markdownExecuted = true"></svg>\n<iframe src="https://markdown-test.invalid/frame"></iframe>';
  await detail.getByLabel('新增留言', { exact: true }).fill(danger);
  const commentEditor = detail.getByRole('group', { name: '新增留言編輯器', exact: true });
  await commentEditor.getByRole('tab', { name: '預覽', exact: true }).click();
  const commentPreview = commentEditor.getByRole('tabpanel', { name: '預覽', exact: true });
  assert.equal(await commentPreview.locator('script, img, svg, iframe, [onerror], [onload]').count(), 0);
  assert.equal(await commentPreview.locator('a[href^="javascript:"], a[href^="data:"]').count(), 0);
  await detail.getByRole('button', { name: '送出留言', exact: true }).click();
  await detail.locator('.comment .markdown-body').getByRole('heading', { name: '安全顯示', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.markdownExecuted === true), false);
  assert.deepEqual(unwantedRequests, []);
  const measurements = [];
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
    if (width === 390) await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${artifacts}/detail-${width}.png`, fullPage: true });
    measurements.push({ width, overflow: false });
  }
  await page.getByRole('button', { name: '編輯任務', exact: true }).click();
  const editor = page.getByRole('region', { name: '編輯任務完整頁', exact: true });
  assert.equal(await editor.getByLabel('描述', { exact: true }).inputValue(), source);
  await editor.getByRole('group', { name: '描述編輯器', exact: true }).getByRole('tab', { name: '預覽', exact: true }).click();
  await editor.screenshot({ path: `${artifacts}/editor-preview-390.png` });
  await editor.getByRole('group', { name: '描述編輯器', exact: true }).getByRole('tab', { name: '編輯', exact: true }).click();
  await editor.screenshot({ path: `${artifacts}/editor-source-390.png` });
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  assert.deepEqual(failures, []);
  writeFileSync(`${artifacts}/checks.json`, JSON.stringify({ measurements, scriptExecuted: false, unwantedRequests }, null, 2));
  console.log('PASS: Markdown toolbar/undo/IME, preview, multi-line TODO source/reload/edit/conversion, card/comments and unsafe HTML/URLs/external image requests, desktop/tablet/mobile');
} finally { await browser?.close(); await vite?.close(); }

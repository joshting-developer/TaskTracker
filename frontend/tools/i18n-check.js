import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const storage = new Map();
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) } });
const { locale, t, setLocale, setLocaleAccount, translateError, formatNumber, formatDate, projectRoleLabel } = await import('../src/i18n/index.js');
const en = JSON.parse(readFileSync(new URL('../src/i18n/en.json', import.meta.url)));
const zh = JSON.parse(readFileSync(new URL('../src/i18n/zh-TW.json', import.meta.url)));
assert.deepEqual(Object.keys(en).sort(), Object.keys(zh).sort());
const placeholders = value => [...value.matchAll(/\{\d+\}/g)].map(match => match[0]).sort();
for (const key of Object.keys(zh)) { assert.equal(typeof en[key], 'string', key); assert.ok(en[key].length, key); assert.deepEqual(placeholders(en[key]), placeholders(zh[key]), key); if (key !== '繁體中文') assert.ok(!/\p{Script=Han}/u.test(en[key]), key); }
assert.equal(locale.value, 'zh-TW');
assert.equal(setLocale('unsupported'), false);
assert.equal(setLocale('en'), true);
assert.equal(t('任務列表'), 'Issue list');
assert.equal(t('進入專案：{0}', ['使用者中文專案']), 'Open project: 使用者中文專案');
assert.equal(t('<img src=x onerror=alert(1)>'), '<img src=x onerror=alert(1)>');
for (const key of ['__proto__', 'constructor', 'toString']) assert.equal(t(key), key);
assert.equal(translateError('FORBIDDEN', '未列入字典的中文訊息'), 'You do not have permission for this action');
assert.equal(translateError('UNKNOWN_NEW_CODE', '未列入字典的中文訊息'), 'Request failed');
assert.equal(projectRoleLabel({ id: 'maintainer', label: '專案管理者' }), 'Project manager');
assert.equal(projectRoleLabel({ id: 'custom', label: '使用者自訂角色' }), '使用者自訂角色');
assert.equal(formatNumber(1234.5), '1,234.5');
assert.match(formatDate('2026-11-15T02:30:00Z', { month: 'long', day: 'numeric' }), /November 15/);
setLocaleAccount('account-a');

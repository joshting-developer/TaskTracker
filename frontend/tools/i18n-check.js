setLocaleAccount('account-a');
assert.equal(locale.value, 'zh-TW', 'Account preferences are isolated');
assert.equal(t('Issue list'), '任務列表');
for (const type of ['Epic','Task','Bug']) assert.equal(t(type), type);
assert.equal(translateError('FORBIDDEN', '原始錯誤'), '原始錯誤');
